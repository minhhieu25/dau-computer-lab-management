-- V1__schema.sql
-- Schema for the 9 entities of Chart/ERD/ERD.png.
-- Naming per Docs/coding_convention.md: snake_case, pk_<table>, fk_<table>_<column>,
-- uk_<table>_<column>, idx_<table>_<column>.
-- Deviations from the ERD (documented, to be confirmed with the team in Sprint 0):
--   * ERD "User" -> physical table "app_user": "user" is a reserved keyword in PostgreSQL.
--   * app_user.deleted_at added: soft delete of accounts is required by BR-09 and
--     flagged as an ERD gap in Docs/Work_Assignment.md.

-- Entity 1: user — accounts of all three roles (admin, teacher, student).
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(50)  NOT NULL,
    password_hash TEXT         NOT NULL, -- Format: pbkdf2-sha256$<iterations>$<salt-b64>$<hash-b64>
    full_name     VARCHAR(150) NOT NULL,
    role          VARCHAR(20)  NOT NULL, -- admin | teacher | student
    status        VARCHAR(20)  NOT NULL, -- active | locked
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ  NULL,     -- Soft delete (BR-09); NULL means the account is active.
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role   CHECK (role IN ('admin', 'teacher', 'student')),
    CONSTRAINT ck_app_user_status CHECK (status IN ('active', 'locked'))
);

-- Entity 2: machine — a lab workstation registered by HELLO.
CREATE TABLE machine (
    machine_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    machine_guid        UUID         NOT NULL,
    hostname            VARCHAR(100) NOT NULL,
    ip_address          VARCHAR(45)  NOT NULL, -- IPv4 or IPv6
    seat_label          VARCHAR(20),
    last_seen_at        TIMESTAMPTZ,
    last_rtt_ms         INTEGER,
    packet_loss_percent NUMERIC(5,2),
    CONSTRAINT pk_machine PRIMARY KEY (machine_id),
    CONSTRAINT uk_machine_machine_guid UNIQUE (machine_guid)
);

-- Entity 3: system_setting — singleton row (system_setting_id is always 1).
CREATE TABLE system_setting (
    system_setting_id INTEGER     NOT NULL,
    retention_days    INTEGER     NOT NULL DEFAULT 30, -- BR-10: default 30 days
    updated_by        BIGINT      NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_system_setting PRIMARY KEY (system_setting_id),
    CONSTRAINT ck_system_setting_singleton CHECK (system_setting_id = 1),
    CONSTRAINT ck_system_setting_retention CHECK (retention_days BETWEEN 1 AND 120),
    CONSTRAINT fk_system_setting_updated_by FOREIGN KEY (updated_by) REFERENCES app_user (user_id)
);

-- Entity 4: student_session — a student logged in on one machine.
CREATE TABLE student_session (
    student_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT      NOT NULL,
    machine_id         BIGINT      NOT NULL,
    login_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    logout_at          TIMESTAMPTZ,
    CONSTRAINT pk_student_session PRIMARY KEY (student_session_id),
    CONSTRAINT fk_student_session_user_id    FOREIGN KEY (user_id)    REFERENCES app_user (user_id),
    CONSTRAINT fk_student_session_machine_id FOREIGN KEY (machine_id) REFERENCES machine (machine_id)
);

-- Entity 5: submission_session — one "collect homework" round opened by a teacher.
CREATE TABLE submission_session (
    submission_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id               BIGINT       NOT NULL, -- Teacher who opened the session.
    session_name          VARCHAR(200) NOT NULL,
    started_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ended_at              TIMESTAMPTZ,
    status                VARCHAR(20)  NOT NULL, -- collecting | completed
    CONSTRAINT pk_submission_session PRIMARY KEY (submission_session_id),
    CONSTRAINT fk_submission_session_user_id FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT ck_submission_session_status  CHECK (status IN ('collecting', 'completed'))
);

-- Entity 6: recording_file — screen recordings, stored only on the server (BR-07).
CREATE TABLE recording_file (
    recording_file_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT       NOT NULL, -- Teacher who recorded.
    student_session_id BIGINT       NOT NULL, -- The monitored student session.
    file_name          VARCHAR(255) NOT NULL,
    file_path          TEXT         NOT NULL,
    started_at         TIMESTAMPTZ  NOT NULL,
    ended_at           TIMESTAMPTZ,
    file_size_bytes    BIGINT,
    status             VARCHAR(20)  NOT NULL, -- recording | stored | deleted
    expires_at         TIMESTAMPTZ  NOT NULL, -- Retention job deletes after this moment (BR-10).
    CONSTRAINT pk_recording_file PRIMARY KEY (recording_file_id),
    CONSTRAINT uk_recording_file_file_path UNIQUE (file_path),
    CONSTRAINT fk_recording_file_user_id            FOREIGN KEY (user_id)            REFERENCES app_user (user_id),
    CONSTRAINT fk_recording_file_student_session_id FOREIGN KEY (student_session_id) REFERENCES student_session (student_session_id),
    CONSTRAINT ck_recording_file_status CHECK (status IN ('recording', 'stored', 'deleted'))
);

-- Entity 7: recording_log — audit log of sensitive actions (BR-10).
CREATE TABLE recording_log (
    recording_log_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT      NOT NULL, -- Who performed the action.
    recording_file_id BIGINT      NOT NULL,
    action            VARCHAR(50) NOT NULL, -- start | stop | view | delete | set_retention ...
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_recording_log PRIMARY KEY (recording_log_id),
    CONSTRAINT fk_recording_log_user_id           FOREIGN KEY (user_id)           REFERENCES app_user (user_id),
    CONSTRAINT fk_recording_log_recording_file_id FOREIGN KEY (recording_file_id) REFERENCES recording_file (recording_file_id)
);

-- Entity 8: submission — one student's homework inside a session.
CREATE TABLE submission (
    submission_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    submission_session_id BIGINT      NOT NULL,
    student_user_id       BIGINT      NOT NULL,
    machine_id            BIGINT      NOT NULL,
    status                VARCHAR(20) NOT NULL, -- submitting | submitted | failed (BR-05 fail-safe)
    submitted_at          TIMESTAMPTZ,
    CONSTRAINT pk_submission PRIMARY KEY (submission_id),
    CONSTRAINT fk_submission_submission_session_id FOREIGN KEY (submission_session_id) REFERENCES submission_session (submission_session_id),
    CONSTRAINT fk_submission_student_user_id       FOREIGN KEY (student_user_id)       REFERENCES app_user (user_id),
    CONSTRAINT fk_submission_machine_id            FOREIGN KEY (machine_id)            REFERENCES machine (machine_id),
    CONSTRAINT ck_submission_status CHECK (status IN ('submitting', 'submitted', 'failed'))
);

-- Entity 9: submission_file — one collected file on the server.
CREATE TABLE submission_file (
    submission_file_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    submission_id      BIGINT       NOT NULL,
    file_name          VARCHAR(255) NOT NULL,
    file_path          TEXT         NOT NULL, -- ThuBai\<teacher>\<datetime>\<IP>_<MSSV>\
    file_size_bytes    BIGINT       NOT NULL,
    CONSTRAINT pk_submission_file PRIMARY KEY (submission_file_id),
    CONSTRAINT uk_submission_file_file_path UNIQUE (file_path),
    CONSTRAINT fk_submission_file_submission_id FOREIGN KEY (submission_id) REFERENCES submission (submission_id)
);

-- Basic indexes. PostgreSQL does not auto-index FK columns.
CREATE INDEX idx_machine_last_seen_at             ON machine (last_seen_at);
CREATE INDEX idx_student_session_user_id          ON student_session (user_id);
CREATE INDEX idx_student_session_machine_id       ON student_session (machine_id);
CREATE INDEX idx_submission_session_user_id       ON submission_session (user_id);
CREATE INDEX idx_recording_file_user_id           ON recording_file (user_id);
CREATE INDEX idx_recording_file_expires_at        ON recording_file (expires_at); -- Retention job scan.
CREATE INDEX idx_recording_log_user_id            ON recording_log (user_id);
CREATE INDEX idx_recording_log_recording_file_id  ON recording_log (recording_file_id);
CREATE INDEX idx_submission_session_status        ON submission_session (status);
CREATE INDEX idx_submission_submission_session_id ON submission (submission_session_id);
CREATE INDEX idx_submission_student_user_id       ON submission (student_user_id);
CREATE INDEX idx_submission_machine_id            ON submission (machine_id);
CREATE INDEX idx_submission_file_submission_id    ON submission_file (submission_id);
